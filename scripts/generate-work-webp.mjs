#!/usr/bin/env node

// Convert static work and case-study media to high-quality WebP.
// The source files stay in public/ so they remain available as fallbacks;
// runtime references use the generated WebP files.
import { mkdir, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';

const require = createRequire(import.meta.url);
const sharp = require('sharp');

const publicDir = join(import.meta.dirname, '..', 'public');
const sources = [
  'assistant-min.jpg',
  'bookshelf-ai-min.jpg',
  'mobile-min.jpg',
  'task-master-min.jpg',
  'taxi-app-min.jpg',
  'video-ai-min.jpg',
  'web-pages-min.jpg',
  'case-studies/luminar-collage/section-1.jpg',
  'case-studies/luminar-collage/section-2.jpg',
  'case-studies/luminar-collage/section-3.jpg',
  'case-studies/luminar-collage/section-4.jpg',
  'case-studies/luminar-collage/section-5.jpg',
];

const responsiveDir = join(publicDir, 'work-images');
await mkdir(responsiveDir, { recursive: true });
const manifest = {};

for (const relativeSource of sources) {
  const source = join(publicDir, relativeSource);
  const output = source.replace(/\.jpg$/i, '.webp');
  await mkdir(dirname(output), { recursive: true });
  await sharp(source).webp({ quality: 90, effort: 5 }).toFile(output);
  const { width, height } = await sharp(source).metadata();
  const widths = [...new Set([640, 1200, 1920, width].filter(size => size <= width))];
  const variants = [];
  for (const size of widths) {
    // Encode directly from the source, avoiding another lossy conversion on request.
    const buffer = await sharp(source).resize({ width: size, withoutEnlargement: true })
      .webp({ quality: 90, effort: 5 }).toBuffer();
    const hash = createHash('sha256').update(buffer).digest('hex').slice(0, 12);
    const name = `${relativeSource.replace(/\.jpg$/i, '').replaceAll('/', '-')}-${size}-${hash}.webp`;
    await writeFile(join(responsiveDir, name), buffer);
    variants.push({ src: `/work-images/${name}`, width: size });
  }
  manifest[`/${relativeSource.replace(/\.jpg$/i, '.webp')}`] = {
    width, height,
    src: (variants.find(variant => variant.width === 1200) ?? variants.at(-1)).src,
    srcSet: variants.map(variant => `${variant.src} ${variant.width}w`).join(', '),
  };
  console.log(`Generated ${output}`);
}

await writeFile(join(publicDir, '..', 'src', 'data', 'workImageSources.ts'),
  `// Generated by npm run images:webp. Filenames contain a content hash for immutable caching.\nexport const workImageSources: Record<string, { src: string; srcSet: string; width: number; height: number }> = ${JSON.stringify(manifest, null, 2)};\n`);
